package main

import "strings"

func isAlpha2(s string) bool {
	return len(s) == 2 && s[0] >= 'A' && s[0] <= 'Z' && s[1] >= 'A' && s[1] <= 'Z'
}

func lookupCountryCode(name string) string {
	name = strings.TrimSpace(name)
	if name == "" {
		return ""
	}
	if isAlpha2(name) {
		return name
	}
	if code, ok := countryCodeMap[name]; ok {
		return code
	}
	lower := strings.ToLower(name)
	if code, ok := countryCodeMap[lower]; ok {
		return code
	}
	return ""
}

